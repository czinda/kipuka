#!/usr/bin/env bash
# demo/setup.sh — generate the demo PKI and kipuka config.
#
# Creates, under demo/pki/:
#   ca.key / ca.crt         demo root CA (EC P-256) — issues everything below
#   server.key / server.crt kipuka's TLS server certificate (SAN localhost/127.0.0.1)
#   client.key / client.crt bootstrap mTLS client identity used to enroll
#
# and writes demo/kipuka-demo.toml pointing at those files with absolute paths
# (kipuka's config validation checks that every referenced file exists).
#
# Everything here is throwaway demo material. Re-run any time; it is idempotent
# unless you pass --force, which regenerates from scratch.

source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

FORCE=0
[[ "${1:-}" == "--force" ]] && FORCE=1

require openssl

if [[ "${FORCE}" == "1" ]]; then
  say "Removing previous demo PKI and state (--force)…"
  rm -rf "${PKI_DIR}" "${STATE_DIR}"
fi

mkdir -p "${PKI_DIR}" "${STATE_DIR}"
chmod 700 "${PKI_DIR}"

# If the CA already exists and we're not forcing, keep it.
if [[ -f "${PKI_DIR}/ca.crt" && "${FORCE}" == "0" ]]; then
  ok "Demo PKI already present at ${PKI_DIR} (use --force to regenerate)."
else
  act "Generating demo PKI (throwaway EC P-256 keys)"

  # ── Root CA ─────────────────────────────────────────────────────────────────
  say "Creating the demo root CA…"
  openssl ecparam -name prime256v1 -genkey -noout -out "${PKI_DIR}/ca.key"
  openssl req -x509 -new -key "${PKI_DIR}/ca.key" -sha256 -days 3650 \
    -subj "/O=kipuka demo/CN=kipuka Demo Root CA" \
    -addext "basicConstraints=critical,CA:TRUE,pathlen:0" \
    -addext "keyUsage=critical,keyCertSign,cRLSign" \
    -out "${PKI_DIR}/ca.crt"
  ok "Root CA → ${PKI_DIR}/ca.crt"

  # ── TLS server certificate ──────────────────────────────────────────────────
  say "Issuing kipuka's TLS server certificate…"
  openssl ecparam -name prime256v1 -genkey -noout -out "${PKI_DIR}/server.key"
  openssl req -new -key "${PKI_DIR}/server.key" \
    -subj "/O=kipuka demo/CN=localhost" -out "${PKI_DIR}/server.csr"
  openssl x509 -req -in "${PKI_DIR}/server.csr" \
    -CA "${PKI_DIR}/ca.crt" -CAkey "${PKI_DIR}/ca.key" -CAcreateserial \
    -days 825 -sha256 \
    -extfile <(printf 'subjectAltName=DNS:localhost,IP:127.0.0.1\nkeyUsage=critical,digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth\n') \
    -out "${PKI_DIR}/server.crt"
  ok "TLS server cert → ${PKI_DIR}/server.crt"

  # ── Bootstrap mTLS client identity ──────────────────────────────────────────
  # This is the credential a device/operator presents to authenticate the
  # enrollment request. kipuka validates it against the EST truststore (ca.crt).
  say "Issuing a bootstrap mTLS client identity…"
  openssl ecparam -name prime256v1 -genkey -noout -out "${PKI_DIR}/client.key"
  openssl req -new -key "${PKI_DIR}/client.key" \
    -subj "/O=kipuka demo/CN=bootstrap-client" -out "${PKI_DIR}/client.csr"
  openssl x509 -req -in "${PKI_DIR}/client.csr" \
    -CA "${PKI_DIR}/ca.crt" -CAkey "${PKI_DIR}/ca.key" -CAcreateserial \
    -days 825 -sha256 \
    -extfile <(printf 'keyUsage=critical,digitalSignature\nextendedKeyUsage=clientAuth\n') \
    -out "${PKI_DIR}/client.crt"
  ok "Bootstrap client cert → ${PKI_DIR}/client.crt"

  rm -f "${PKI_DIR}"/*.csr "${PKI_DIR}"/*.srl
  chmod 600 "${PKI_DIR}"/*.key
fi

# ── Config ────────────────────────────────────────────────────────────────────
act "Writing kipuka demo config → ${CONFIG_FILE}"
cat > "${CONFIG_FILE}" <<TOML
# kipuka-demo.toml — generated by demo/setup.sh. Do not hand-edit; re-run setup.
#
# Scope: this config exercises ONLY capabilities that are wired and working at
# runtime — RFC 7030 EST (cacerts/enroll/reenroll/csrattrs) over mTLS, STAR
# server-driven renewal, the tamper-evident audit chain, and the read-only
# admin/audit API. Not-yet-wired features (Multi-CA HA, CoAP DTLS, /fullcmc,
# server-side keygen, OTP auth, PQC issuance) are intentionally left disabled.

[server]
listen_addr = "${HOST}:${PORT}"
max_body_size = 1048576

[tls]
enabled = true
cert_file = "${PKI_DIR}/server.crt"
key_file  = "${PKI_DIR}/server.key"
# EST client truststore: client certs are validated against the demo CA.
ca_file   = "${PKI_DIR}/ca.crt"
# "optional": /cacerts and /csrattrs work anonymously; enrollment presents mTLS.
client_auth = "optional"
min_protocol = "1.2"
max_protocol = "1.3"

[database]
url = "sqlite://${DB_FILE}?mode=rwc"
run_migrations = true
sqlite_wal = true

[[ca]]
id = "demo"
is_default = true
cert_file = "${PKI_DIR}/ca.crt"
key_file  = "${PKI_DIR}/ca.key"
common_name = "kipuka Demo Issuing CA"
organization = "kipuka demo"
validity_days = 90
hash_algorithm = "sha256"

[est]
simpleenroll = true
simplereenroll = true
csrattrs = true

[star]
# Server-driven renewal (RFC 8739 model over EST): the server re-issues on a
# schedule and devices fetch the current certificate with a plain GET.
enabled = true
min_renewal_interval_secs = 3600
max_renewal_interval_secs = 604800
default_renewal_interval_secs = 86400
max_lifetime_days = 30

[audit]
enabled = true
log_to_db = true
# Keyed HMAC-SHA256 hash chain (NIAP FAU_STG.1). The key is read from the
# environment so it never lives in the config file.
integrity_key = "env:KIPUKA_AUDIT_KEY"

[admin]
enabled = true
auth_method = "bearer"
# Read from the environment — never a plaintext token in the config file.
bearer_token = "env:KIPUKA_ADMIN_TOKEN"
TOML

ok "Config written."
say "Demo PKI + config ready. Next: ${BOLD}./demo/run.sh${RESET}"
